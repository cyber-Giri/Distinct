import type { Analysis, Coverage, SimilarProject } from "@/lib/types";

const cov = (s: string): Coverage[] =>
  s.split("").map((c) => (c === "F" ? "full" : c === "P" ? "partial" : "none"));

type P = Omit<SimilarProject, "coverage" | "id"> & { cov: string };
const projects = (prefix: string, list: P[]): SimilarProject[] =>
  list.map(({ cov: c, ...p }, i) => ({ ...p, id: `${prefix}-p${i + 1}`, coverage: cov(c) }));

